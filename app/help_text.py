def render_html(title: str, items: list) -> str:
    """把一个分类渲染成 QTextBrowser 能吃的 HTML。"""
    parts = ["<h2 style='margin:2px 0 8px 0;'>&nbsp;%s</h2>" % title]
    in_list = False
    for raw in items:
        text = str(raw).strip()
        if not text:
            continue
        if text.startswith("## "):          # 小结标题
            if in_list:
                parts.append("</ul>")
                in_list = False
            parts.append("<h3 style='margin:12px 0 4px 0;'>&nbsp;%s</h3>"
                         % text[3:].strip())
            continue
        if not in_list:
            parts.append("<ul style='margin:2px 0 2px 0;'>")
            in_list = True
        parts.append("<li style='margin:3px 0;'>%s</li>" % text)
    if in_list:
        parts.append("</ul>")
    return "\n".join(parts)
